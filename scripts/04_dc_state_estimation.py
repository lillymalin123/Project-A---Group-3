"""DC state estimation and bad-data detection on the DC subset of the frozen baseline measurements (no attack).

Run from anywhere:  python scripts/04_dc_state_estimation.py   (after 01_generate_measurements.py)
The DC estimator sees the P flows, P injections and angles of the SAME draw the AC estimator uses
(data/measurements_baseline.csv), with zero active injection enforced at zero-injection buses.
Writes results/dc_se_estimate.csv (true and estimated angle per bus) and results/dc_bad_data.csv (one row:
chi-square statistic, dof, threshold, p-value, alarm, largest normalized residual; same columns as
results/ac_bad_data.csv, plus J of the noise-free AC data = the DC model mismatch alone).
An ALARM is a result, not an error: the data come from the AC power flow, which the DC model cannot
reproduce exactly. The script exits non-zero only if a self-check fails.
Library: src/dc_state_estimation.py.  Answer-key test of the same library: tests/test_dc_3bus.py.
"""
import sys
from pathlib import Path

import numpy as np
import pandas as pd

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))
import config
from ac_state_estimation import (build_model, chi_square_test, load_measurements, normalized_residuals,
                                 residual_variances)
from common import check, load_case
from dc_state_estimation import (dc_bus_matrices, dc_measurement_matrix, dc_subset, dc_zero_injection_matrix,
                                 estimate_dc)

m = build_model()
meas = dc_subset(load_measurements(config.MEASUREMENTS_CSV))
nb = m["nb"]
H, C = dc_measurement_matrix(m, meas), dc_zero_injection_matrix(m)
ok = []

print("Self-checks")
# 1. the DC network matrix is the Lecture 7 model: B built from data/case57-se.json (branch order irrelevant)
lec = load_case()
B_lec = np.zeros((nb, nb))
for i, j, x in zip(lec["frm"], lec["to"], lec["x"]):
    i0, j0 = i - 1, j - 1
    B_lec[[i0, j0], [i0, j0]] += 1.0 / x
    B_lec[[i0, j0], [j0, i0]] -= 1.0 / x
err_B = np.abs(dc_bus_matrices(m)[1].toarray() - B_lec).max()
ok.append(check(err_B < config.RECOVERY_TOL, f"DC bus matrix equals the Lecture 7 B from case57-se.json (max diff {err_B:.1e})"))

# 2. data generated BY the DC model are recovered exactly. Test state: the AC angles projected onto the
#    zero-injection constraints C theta = 0 (deterministic, realistic size).
th = np.delete(m["Va_true"], m["ref"])
Cd = C.toarray()
theta0 = th - Cd.T @ np.linalg.solve(Cd @ Cd.T, Cd @ th)
lin = estimate_dc(m, meas.assign(value=H @ theta0))
err_lin = np.abs(lin["theta"] - theta0).max()
ok.append(check(err_lin < config.RECOVERY_TOL, f"noise-free DC-model data recover the state (max error {err_lin:.1e})"))

# 3. the actual estimate: constraints and dof
est = estimate_dc(m, meas)
test = chi_square_test(est)
var = residual_variances(est)
w = est["weights"]
viol = np.abs(C @ est["theta"]).max()
ok.append(check(viol < config.CONSTRAINT_TOL, f"zero-injection constraints hold at the estimate ({viol:.1e} p.u.)"))
ok.append(check(test["dof"] == est["n_meas"] - est["n_states"] + est["n_constraints"],
                f"dof = m - n + c = {est['n_meas']} - {est['n_states']} + {est['n_constraints']} = {test['dof']}"))
ok.append(check(abs(np.sum(w * var) - test["dof"]) < config.DOF_CHECK_TOL * test["dof"],
                f"sum(w_i * Omega_ii) = {np.sum(w * var):.3f} equals dof"))

# --- results -----------------------------------------------------------------------------------------
rn = normalized_residuals(est)
worst = int(np.nanargmax(rn))
above = int(np.nansum(rn > config.LNR_THRESHOLD))
n_crit = int(np.isnan(rn).sum())
J_mismatch = chi_square_test(estimate_dc(m, meas.assign(value=meas["true"])))["J"]  # no noise: model error only

row = meas.iloc[worst]
print(f"\nDC estimator: {est['n_meas']} measurements, {est['n_states']} states, {est['n_constraints']} constraints")
print(f"Chi-square test (alpha = {config.ALPHA}): J = {test['J']:.1f}, dof = {test['dof']}, "
      f"threshold = {test['tau']:.1f}, p = {test['p_value']:.2g} -> {'ALARM' if test['alarm'] else 'passes'}")
print(f"  for comparison, DC model mismatch alone (noise-free AC data): J = {J_mismatch:.1f}")
print(f"Largest normalized residual: {rn[worst]:.2f} ({row['type']} {row['side']} index {row['element']}); "
      f"{above} measurement(s) above {config.LNR_THRESHOLD}; {n_crit} critical measurement(s)")

out = pd.DataFrame({"bus": m["bus_numbers"], "Va_true_deg": np.degrees(m["Va_true"]), "Va_dc_deg": np.degrees(est["Va"])})
out["Va_err_deg"] = out["Va_dc_deg"] - out["Va_true_deg"]
print(f"max |Va error| = {out['Va_err_deg'].abs().max():.3f} deg (bus {int(out.loc[out['Va_err_deg'].abs().idxmax(), 'bus'])})")

config.RESULTS_DIR.mkdir(exist_ok=True)
out.to_csv(config.RESULTS_DIR / "dc_se_estimate.csv", index=False)
pd.DataFrame([{
    "J": test["J"], "m": est["n_meas"], "n": est["n_states"], "c": est["n_constraints"], "dof": test["dof"],
    "alpha": config.ALPHA, "tau": test["tau"], "p_value": test["p_value"], "alarm": test["alarm"],
    "largest_norm_resid": rn[worst], "lnr_type": row["type"], "lnr_side": row["side"],
    "lnr_element_0based": int(row["element"]), "lnr_threshold": config.LNR_THRESHOLD,
    "n_above_lnr_threshold": above, "n_critical": n_crit, "J_model_mismatch_noise_free": J_mismatch,
}]).to_csv(config.RESULTS_DIR / "dc_bad_data.csv", index=False)
print(f"wrote {config.RESULTS_DIR / 'dc_se_estimate.csv'} and {config.RESULTS_DIR / 'dc_bad_data.csv'}")
if not all(ok):
    sys.exit("some checks FAILED")
