"""
monte_carlo.py --- Q3: Monte Carlo check of the chi-square bad-data test without attack.

Library only: no printing, no file writing. Called by scripts/06_q3_monte_carlo.py (the draws) and
scripts/07_q3_chi2_analysis.py (the statistics and figures).

Theory being tested (Lectures 3/6; Hug & Giampapa 2012, Sec. IV):
  * Linear model z = Hx + e, e ~ N(0, R), WLS with c independent linear equality constraints:
    the whitened residual is the projection of the whitened noise onto a subspace of dimension
    dof = m - n + c, so J = r'Wr ~ chi2(dof) EXACTLY. Mean dof, variance 2 dof.
  * AC model z = h(x) + e: the same holds only after linearising h around the true state, so
    J ~ chi2(dof) APPROXIMATELY; the curvature of h enters at higher order in sigma. linearised_residual_operator
    gives the exactly-chi2 linearised statistic J_lin for the same noise, so J - J_lin measures that effect.
  * DC estimator on data generated by the AC power flow: the model is linear but wrong. The data are
    z = h_AC(x_true) + e, so the whitened residual is P (d + e_w) with a fixed mismatch d. Then
    J ~ noncentral chi2(dof, lambda) EXACTLY, with lambda = J of the noise-free data. Weights 1/sigma^2
    make lambda(sigma) = lambda(sigma_0) * (sigma_0 / sigma)^2.
All units p.u. (P, Q, Vm) and rad (Va); one sigma for every measurement type, as in the brief.
"""
import numpy as np
from scipy.stats import chi2, kstest, ncx2, norm

from ac_state_estimation import chi_square_test, estimate_ac, jacobian, zero_injection_rows
from dc_state_estimation import dc_subset, estimate_dc


# ----------------------------------------------------------------------------- one noise draw
def noisy_copy(meas, sigma, rng):
    """A new draw of the measurement table: value = true + N(0, sigma^2), and sigma set to ``sigma`` on
    every row (so the estimators weight with 1/sigma^2). ``meas`` needs columns true, sigma, value;
    ``rng`` is a numpy Generator. The input table is not modified."""
    return meas.assign(sigma=sigma, value=meas["true"].to_numpy() + rng.normal(0.0, sigma, len(meas)))


def linearised_residual_operator(m, meas):
    """S = I - H N H' W of the AC estimator LINEARISED at the true state, shape (518, 518).

    H = Jacobian of h and C = Jacobian of the zero-injection constraints, both at x_true;
    N = G^-1 - G^-1 C' (C G^-1 C')^-1 C G^-1, G = H'WH. For noise e the linearised residual is r = S e and
    J_lin = r'Wr ~ chi2(dof) EXACTLY (trace(S) = dof). The nonlinear estimator's J differs from J_lin only
    through the curvature of h, so J_AC - J_lin on the same draw isolates that effect.
    Built with equal weights on every row (one sigma for all measurements, as in the Monte Carlo); S does
    not depend on the value of that sigma (W cancels against G^-1), so it is built once.
    """
    H = jacobian(m, meas, m["Vm_true"], m["Va_true"]).toarray()
    C = jacobian(m, zero_injection_rows(m), m["Vm_true"], m["Va_true"]).toarray()
    Ginv = np.linalg.inv(H.T @ H)
    N = Ginv - Ginv @ C.T @ np.linalg.solve(C @ Ginv @ C.T, C @ Ginv)
    return np.eye(len(meas)) - H @ N @ H.T


def run_draw(m, meas_draw, S_lin=None):
    """AC and DC estimation of ONE noise draw (no attack); both estimators see the same draw, the DC
    estimator only its P-flow, P-injection and angle rows.

    ``S_lin`` (optional): output of linearised_residual_operator; then J_lin_ac is computed from the noise
    e = value - true of the same draw.
    Returns a dict:
      converged_ac  False if estimate_ac raised RuntimeError (no convergence or singular gain matrix);
                    the AC entries are then NaN
      iterations_ac Gauss-Newton iterations used
      J_ac, J_dc    chi-square statistics r'Wr (dimensionless)
      J_lin_ac      the same statistic for the AC estimator linearised at x_true (exactly chi2(dof));
                    only if S_lin is given
      max_dVa_ac    max |Va_hat - Va_true| over buses (rad): flags a run that converged to a wrong point
      max_dVm_ac    max |Vm_hat - Vm_true| over buses (p.u.)
    """
    out = {"converged_ac": True}
    if S_lin is not None:
        e = meas_draw["value"].to_numpy() - meas_draw["true"].to_numpy()
        r = S_lin @ e
        out["J_lin_ac"] = float(r @ (r / meas_draw["sigma"].to_numpy() ** 2))
    try:
        est = estimate_ac(m, meas_draw)
        out.update(iterations_ac=est["iterations"], J_ac=chi_square_test(est)["J"],
                   max_dVa_ac=float(np.abs(est["Va"] - m["Va_true"]).max()),
                   max_dVm_ac=float(np.abs(est["Vm"] - m["Vm_true"]).max()))
    except RuntimeError:
        out.update(converged_ac=False, iterations_ac=np.nan, J_ac=np.nan, max_dVa_ac=np.nan, max_dVm_ac=np.nan)
    out["J_dc"] = chi_square_test(estimate_dc(m, dc_subset(meas_draw)))["J"]  # linear: always solvable
    return out


def reference_values(m, meas, sigma, alpha):
    """Degrees of freedom, thresholds and the DC noncentrality at one sigma (no randomness).

    ``meas`` is the full AC table (its 'true' column = h(x_true) is used). Returns a dict:
      dof_ac, tau_ac   m - n + c of the AC estimator and the (1 - alpha) quantile of chi2(dof_ac)
      dof_dc, tau_dc   the same for the DC estimator
      lambda_dc        noncentrality: J of the DC estimator on the noise-free AC data, weights 1/sigma^2
    """
    clean = meas.assign(sigma=sigma, value=meas["true"])
    t_ac = chi_square_test(estimate_ac(m, clean), alpha)
    t_dc = chi_square_test(estimate_dc(m, dc_subset(clean)), alpha)
    return {"dof_ac": t_ac["dof"], "tau_ac": t_ac["tau"], "dof_dc": t_dc["dof"], "tau_dc": t_dc["tau"],
            "lambda_dc": t_dc["J"]}


# ----------------------------------------------------------------------------- statistics of J
def wilson_interval(k, n, level=0.95):
    """Wilson score interval for a binomial proportion k/n (stays inside [0, 1], also at k = 0 or n)."""
    if n == 0:
        return np.nan, np.nan
    z = norm.ppf(0.5 + level / 2)
    p = k / n
    centre = (p + z**2 / (2 * n)) / (1 + z**2 / n)
    half = z * np.sqrt(p * (1 - p) / n + z**2 / (4 * n**2)) / (1 + z**2 / n)
    return centre - half, centre + half


def chi2_summary(J, dof, tau, lam=0.0):
    """Compare a sample of test statistics with chi2(dof) (lam = 0) or noncentral chi2(dof, lam).

    J    sample of statistics of the CONVERGED runs (NaN entries are dropped here)
    tau  detection threshold actually used (the central chi2 95 % quantile, as in the estimator)
    Returns a dict with
      n, mean, var                          sample size, sample mean and variance of J
      mean_theory, var_theory               dof + lam and 2 (dof + 2 lam)
      z_mean, z_var                         (sample - theory) / standard error under the theory:
                                            SE(mean) = sqrt(var_theory / n); for the central case
                                            SE(var) = sqrt((8 dof^2 + 48 dof) / n) (4th central moment of
                                            chi2: 12 dof^2 + 48 dof); |z| > 2 is a significant deviation
      far, far_lo, far_hi                   empirical false-alarm rate P(J > tau) and its 95 % Wilson interval
      far_theory                            P(J > tau) under the theory (alpha for lam = 0)
      q95                                   empirical 95 % quantile of J (a threshold calibrated by simulation)
      ks_p                                  Kolmogorov-Smirnov p-value against the theoretical distribution
    """
    J = np.asarray(J, dtype=float)
    J = J[np.isfinite(J)]
    n = len(J)
    dist = chi2(dof) if lam == 0 else ncx2(dof, lam)
    mean_th, var_th = dist.mean(), dist.var()
    k = int(np.sum(J > tau))
    lo, hi = wilson_interval(k, n)
    se_var = np.sqrt((8 * dof**2 + 48 * dof) / n) if lam == 0 else np.nan
    return {
        "n": n, "mean": J.mean(), "var": J.var(ddof=1), "mean_theory": mean_th, "var_theory": var_th,
        "z_mean": (J.mean() - mean_th) / np.sqrt(var_th / n), "z_var": (J.var(ddof=1) - var_th) / se_var,
        "far": k / n, "far_lo": lo, "far_hi": hi, "far_theory": float(dist.sf(tau)),
        "q95": float(np.quantile(J, 0.95)), "ks_p": float(kstest(J, dist.cdf).pvalue),
    }


def qq_points(J, dof):
    """Q-Q plot coordinates: theoretical chi2(dof) quantiles at plotting positions (i - 0.5)/n against the
    sorted sample. NaN entries are dropped. Returns (theoretical, empirical)."""
    J = np.sort(np.asarray(J, dtype=float)[np.isfinite(J)])
    p = (np.arange(1, len(J) + 1) - 0.5) / len(J)
    return chi2.ppf(p, dof), J
